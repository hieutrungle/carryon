"""Run cards: a generated card.md per run directory.

Usage: ``python -m carryon.eval.run_card runs/<run_id> [--figures-dir figures]``

Figure links come from ``figures/<ID>.inputs.json`` files, a JSON list of the run ids a figure
script read; figure scripts write them next to ``<ID>.png`` (M0.6).
"""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, TypeAdapter
from pydantic_settings import CliApp, CliPositionalArg

from carryon.run import RunDir, RunInfo, load_run_info

_FIGURE_INPUTS = TypeAdapter(list[str])


def render_card(run: RunDir, figures_dir: Path = Path("figures")) -> str:
    info = load_run_info(run)
    sections = [
        f"# Run `{info.run_id}`\n",
        "*Generated by `carryon.eval.run_card`; do not edit.*\n",
        *_dirty_warning(info),
        _overview(info),
        _summary(info),
        _software(info),
        _files(run),
        _figures(info.run_id, figures_dir),
        _config(run),
    ]
    return "\n".join(sections)


def write_card(run: RunDir, figures_dir: Path = Path("figures")) -> Path:
    run.card.write_text(render_card(run, figures_dir), encoding="utf-8")
    return run.card


def _dirty_warning(info: RunInfo) -> list[str]:
    if info.git_dirty:
        return [
            "**Warning:** uncommitted changes; the git commit does not fully describe the code.\n"
        ]
    return []


def _overview(info: RunInfo) -> str:
    duration = "running"
    if info.finished_at is not None:
        duration = f"{(info.finished_at - info.started_at).total_seconds() / 60:.1f} min"
    rows = [
        ("Kind", info.kind),
        ("Status", info.status),
        ("Started (UTC)", f"{info.started_at:%Y-%m-%d %H:%M:%S}"),
        ("Duration", duration),
        ("Config", f"`{info.config_name}` (sha256 `{info.config_sha256[:12]}`)"),
        ("Seed", str(info.seed)),
        ("Git commit", f"`{info.git_commit}`" if info.git_commit else "unknown"),
        ("Host", info.host),
        ("Slurm job", info.slurm_job_id or "none"),
        ("GPUs", ", ".join(info.gpus) or "none"),
    ]
    return "## Overview\n\n" + _table(("Field", "Value"), rows)


def _summary(info: RunInfo) -> str:
    if not info.summary:
        return "## Final metrics\n\nNone recorded yet.\n"
    rows = [(name, f"{value:.4g}") for name, value in sorted(info.summary.items())]
    return "## Final metrics\n\n" + _table(("Metric", "Value"), rows)


def _software(info: RunInfo) -> str:
    rows = [("python", info.python), *sorted(info.packages.items())]
    return "## Software\n\n" + _table(("Package", "Version"), rows)


def _files(run: RunDir) -> str:
    files = sorted(p for p in run.path.iterdir() if p.is_file() and p != run.card)
    rows = [(f"`{p.name}`", _size(p.stat().st_size)) for p in files]
    return "## Files\n\n" + _table(("File", "Size"), rows)


def _figures(run_id: str, figures_dir: Path) -> str:
    ids = []
    for inputs in sorted(figures_dir.glob("*.inputs.json")):
        if run_id in _FIGURE_INPUTS.validate_json(inputs.read_bytes()):
            ids.append(inputs.name.removesuffix(".inputs.json"))
    if not ids:
        return "## Figures\n\nNo figure uses this run yet.\n"
    # Cards live in runs/<run_id>/, figures in figures/, both at the repo root.
    links = "\n".join(f"- [{fid}](../../figures/{fid}.png)" for fid in ids)
    return f"## Figures\n\n{links}\n"


def _config(run: RunDir) -> str:
    return f"## Config\n\n```yaml\n{run.config.read_text(encoding='utf-8').rstrip()}\n```\n"


def _table(header: tuple[str, str], rows: list[tuple[str, str]]) -> str:
    lines = [f"| {header[0]} | {header[1]} |", "| --- | --- |"]
    lines += [f"| {a} | {b} |" for a, b in rows]
    return "\n".join(lines) + "\n"


def _size(n_bytes: int) -> str:
    size = float(n_bytes)
    for unit in ("B", "kB", "MB"):
        if size < 1000:
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1000
    return f"{size:.1f} GB"


class RunCardCli(BaseModel):
    """Write card.md for one run directory."""

    run_dir: CliPositionalArg[Path]
    figures_dir: Path = Path("figures")

    def cli_cmd(self) -> None:
        print(write_card(RunDir(path=self.run_dir), self.figures_dir))


def main(argv: list[str] | None = None) -> None:
    CliApp.run(RunCardCli, cli_args=argv)


if __name__ == "__main__":
    main()
