"""Run directories: every run writes the same files, so cards and figures rebuild from disk alone.

runs/<run_id>/
    config.yaml             exact copy of the experiment config
    run.json                RunInfo: identity, code state, environment, final metrics
    trajectories.jsonl      one Episode per line while the run is going; gzipped on finish
    trajectories.jsonl.gz   the same file after ``finish_run``
    metrics.parquet         one row per training step or eval episode, written by its producer
    card.md                 generated by ``carryon.eval.run_card``; never hand-edited

A run id is ``<UTC yyyymmdd-HHMMSS>-<config stem>-s<seed>``, e.g.
``20261025-153012-grpo_append_qwen35-4b_8k-s0``.
"""

from __future__ import annotations

import gzip
import hashlib
import os
import platform
import shutil
import subprocess
from dataclasses import dataclass
from datetime import UTC, datetime
from importlib import metadata
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

REPO_ROOT = Path(__file__).resolve().parents[1]
TRAJECTORIES = "trajectories.jsonl"

RunKind = Literal["smoke", "eval", "sft", "grpo"]
RunStatus = Literal["running", "finished", "failed"]

# Versions worth recording when present; a missing package is simply left out.
TRACKED_PACKAGES = (
    "carryon",
    "pydantic",
    "torch",
    "transformers",
    "vllm",
    "trl",
    "peft",
    "unsloth",
)


class RunInfo(BaseModel):
    """Contents of run.json."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    run_id: str
    kind: RunKind
    config_name: str  # the config path as given, e.g. configs/m4/grpo_append_qwen35-4b_8k.yaml
    config_sha256: str
    seed: int
    git_commit: str | None  # None when not run from a git checkout
    git_dirty: bool | None
    status: RunStatus = "running"
    started_at: datetime
    finished_at: datetime | None = None
    host: str
    slurm_job_id: str | None
    gpus: list[str]
    python: str
    packages: dict[str, str]
    summary: dict[str, float] = Field(default_factory=dict)


@dataclass(frozen=True, slots=True, kw_only=True)
class RunDir:
    """Paths inside one run directory."""

    path: Path

    @property
    def run_id(self) -> str:
        return self.path.name

    @property
    def config(self) -> Path:
        return self.path / "config.yaml"

    @property
    def info(self) -> Path:
        return self.path / "run.json"

    @property
    def metrics(self) -> Path:
        return self.path / "metrics.parquet"

    @property
    def card(self) -> Path:
        return self.path / "card.md"

    @property
    def trajectories(self) -> Path:
        """Where the rollout loop appends episodes while the run is going."""
        return self.path / TRAJECTORIES

    def trajectories_file(self) -> Path:
        """The trajectory file to read: the gzipped one once the run has finished."""
        gz = self.path / f"{TRAJECTORIES}.gz"
        return gz if gz.exists() else self.trajectories


def make_run_id(config_path: Path, seed: int, now: datetime) -> str:
    return f"{now.astimezone(UTC):%Y%m%d-%H%M%S}-{config_path.stem}-s{seed}"


def create_run(
    config_path: Path,
    *,
    kind: RunKind,
    seed: int,
    runs_root: Path = Path("runs"),
    now: datetime | None = None,
) -> RunDir:
    """Create runs/<run_id>/ with the config copy and run.json; refuse to reuse a directory."""
    now = now or datetime.now(UTC)
    run = RunDir(path=runs_root / make_run_id(config_path, seed, now))
    run.path.mkdir(parents=True, exist_ok=False)
    shutil.copyfile(config_path, run.config)
    commit = _git("rev-parse", "HEAD")
    status = _git("status", "--porcelain", "--untracked-files=no")
    info = RunInfo(
        run_id=run.run_id,
        kind=kind,
        config_name=str(config_path),
        config_sha256=hashlib.sha256(config_path.read_bytes()).hexdigest(),
        seed=seed,
        git_commit=commit,
        git_dirty=None if status is None else status != "",
        started_at=now,
        host=platform.node(),
        slurm_job_id=_slurm_job_id(),
        gpus=_gpu_names(),
        python=platform.python_version(),
        packages=_package_versions(),
    )
    write_run_info(run, info)
    return run


def finish_run(
    run: RunDir,
    summary: dict[str, float],
    *,
    status: RunStatus = "finished",
    now: datetime | None = None,
) -> RunInfo:
    """Record final metrics, gzip the trajectories and write card.md."""
    # Imported here because run_card depends on this module.
    from carryon.eval.run_card import write_card

    _gzip_trajectories(run)
    info = load_run_info(run).model_copy(
        update={"status": status, "finished_at": now or datetime.now(UTC), "summary": summary}
    )
    write_run_info(run, info)
    write_card(run)
    return info


def load_run_info(run: RunDir) -> RunInfo:
    return RunInfo.model_validate_json(run.info.read_text(encoding="utf-8"))


def write_run_info(run: RunDir, info: RunInfo) -> None:
    run.info.write_text(info.model_dump_json(indent=2) + "\n", encoding="utf-8")


def _gzip_trajectories(run: RunDir) -> None:
    # Compress only once the run is over: a job killed mid-write leaves a plain JSONL file, whose
    # complete lines stay readable, instead of a gzip stream that breaks at the cut.
    src = run.trajectories
    if not src.exists():
        return
    dst = run.path / f"{TRAJECTORIES}.gz"
    tmp = run.path / f"{TRAJECTORIES}.gz.tmp"
    with src.open("rb") as fin, gzip.open(tmp, "wb") as fout:
        shutil.copyfileobj(fin, fout)
    tmp.replace(dst)
    src.unlink()


def _git(*args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, check=False
        )
    except FileNotFoundError:
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def _slurm_job_id() -> str | None:
    job = os.environ.get("SLURM_JOB_ID")
    task = os.environ.get("SLURM_ARRAY_TASK_ID")
    return f"{job}_{task}" if job and task else job


def _gpu_names() -> list[str]:
    try:
        result = subprocess.run(
            ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError:
        return []
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def _package_versions() -> dict[str, str]:
    versions = {}
    for name in TRACKED_PACKAGES:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            continue
    return versions
